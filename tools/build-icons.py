"""Builds assets/icons.js from the Phosphor icon set (MIT licence, phosphoricons.com).

Usage: python -I tools/build-icons.py <path to @phosphor-icons/web package/src>
Only the icons listed in WANT are copied, as SVG path data on a 1024 grid.
"""
import json
import sys
from pathlib import Path

WANT = {
    'regular': [
        'house', 'cards', 'target', 'exam', 'microphone', 'airplane-tilt', 'translate', 'speaker-high', 'stop',
        'x', 'arrow-left', 'arrow-right', 'caret-right', 'check', 'check-circle', 'x-circle', 'star', 'fire',
        'calendar-blank', 'clock', 'file-text', 'question', 'lightning', 'brain', 'trophy', 'medal', 'play',
        'printer', 'arrow-counter-clockwise', 'lightbulb', 'warning', 'flask', 'map-pin', 'squares-four',
        'list-numbers', 'calculator', 'eye', 'check-square', 'atom', 'bowl-food', 'clipboard-text', 'drop',
        'heartbeat', 'grains-slash', 'first-aid', 'fork-knife', 'baby', 'baby-carriage', 'leaf', 'egg',
        'hand-heart', 'cooking-pot', 'thermometer-simple', 'users-three', 'chart-bar', 'handshake',
        'chats-circle', 'footprints', 'plant', 'seal-check', 'calendar-check', 'compass', 'graduation-cap',
        'hand-waving', 'arrow-square-out', 'sparkle', 'book-open-text', 'timer', 'flag-checkered', 'sun-horizon',
        'arrow-up-right', 'rocket-launch', 'magnifying-glass', 'gauge',
    ],
    'fill': ['star', 'fire', 'check-circle', 'x-circle', 'lightning', 'trophy', 'seal-check', 'play', 'medal', 'sparkle'],
}


def load(src, weight):
    folder = Path(src) / weight
    data = json.loads((folder / 'selection.json').read_text(encoding='utf-8'))
    out = {}
    for ic in data['icons']:
        name = ic['properties']['name'].split(',')[0].strip()
        if weight == 'fill':
            name = name.removesuffix('-fill')
        out[name] = ic['icon']['paths']
    return out


def main(src):
    result = {}
    for weight, names in WANT.items():
        found = load(src, weight)
        missing = [n for n in names if n not in found]
        if missing:
            sys.exit(f'missing {weight} icons: {missing}')
        for n in names:
            key = n if weight == 'regular' else f'{n}-fill'
            result[key] = ' '.join(found[n])
    js = ('// Phosphor icons (MIT licence, phosphoricons.com), regenerated by tools/build-icons.py. Path data on a 1024 grid.\n'
          'const ICONS = ' + json.dumps(result, separators=(',', ':')) + ';\n')
    Path('assets/icons.js').write_text(js, encoding='utf-8')
    print(f'{len(result)} icons, {len(js) // 1024} KB')


if __name__ == '__main__':
    main(sys.argv[1])
